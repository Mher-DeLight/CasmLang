#include "../include/IrGenerator.h"

// == HELPERS ==
void ocarlang::IrGenerator::load_ast(std::unique_ptr<ScopeBlock> ast) {
    entry_point = std::move(ast);
}
std::vector<std::unique_ptr<ocarlang::Ir>> ocarlang::IrGenerator::give_ir() {
    return std::move(ir);
}

void ocarlang::IrGenerator::generate_ir() {
    entry_point->accept(*this);
}
void ocarlang::IrGenerator::print_ir(std::ostream& stream) {
    for (auto& irnode : ir) {
        irnode->print(stream);
        stream << "\n";
    }
}
std::string ocarlang::IrGenerator::generateLabel() {
    return "autogeneratedLabel__ocarLang" +
           std::to_string(
               labelCounter++); // weird name to decrease collision with user-defined labels
}

// == VISIT ==
void ocarlang::IrGenerator::visit(ScopeBlock& node) {
    for (auto& child : node.children) {
        child->accept(*this);
    }
};
