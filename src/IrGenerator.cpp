void ocarlang::IrGenerator::visit(IfStatement& node) {
    std::string jumpName = condMap.at(node.cond);
    std::string trueLabel = generateLabel();
    std::string endLabel = generateLabel();

    ir.push_back(std::make_unique<IrJmp>(trueLabel, jumpName));
    ir.push_back(std::make_unique<IrJmp>(endLabel));
    ir.push_back(std::make_unique<IrLabelStmt>(trueLabel));
    node.scope->accept(*this);
    ir.push_back(std::make_unique<IrLabelStmt>(endLabel));
};
void ocarlang::IrGenerator::visit(Compare& node) {
    node.left->accept(*this);
    auto left = get_current_as<IrMemName>();

    node.right->accept(*this);
    auto right = get_current_as<IrExpr>();

    ir.push_back(std::make_unique<IrCmp>(std::move(left), std::move(right)));
}
void ocarlang::IrGenerator::visit(RegisterName& node) {
    currentNode = std::make_unique<IrMemName>(node.name);
}
void ocarlang::IrGenerator::visit(SyscallStatement& node) {
    ir.push_back(std::make_unique<IrSyscall>());
}
void ocarlang::IrGenerator::visit(ArithmeticOperation& node) {
    node.left->accept(*this);
    auto left = get_current_as<IrMemName>("expected left to be a memory name");

    node.right->accept(*this);
    auto right = get_current_as<IrExpr>("expected right to be a memory name");

    using BO = BinaryOperation;
    std::unique_ptr<IrOp> op;
    switch (node.operation) {
        case BO::ADD:
            op = std::make_unique<IrAdd>(std::move(left), std::move(right));
            break;
        case BO::SUBTRACT:
            op = std::make_unique<IrSub>(std::move(left), std::move(right));
            break;
        case BO::MULTIPLY:
            op = std::make_unique<IrImul>(std::move(left), std::move(right));
            break;
        default:
            break;
    }
    if (!op) {
        panic("Invalid binary operation at " + std::to_string(node.location.row) + ":" +
              std::to_string(node.location.column));
    }
    ir.push_back(std::move(op));
}
void ocarlang::IrGenerator::visit(RawAssignment& node) {
    node.left->accept(*this);
    auto left = get_current_as<IrMemName>();

    node.right->accept(*this);
    auto right = get_current_as<IrExpr>();

    ir.push_back(std::make_unique<IrMovStmt>(std::move(left), std::move(right)));
}
void ocarlang::IrGenerator::visit(RawLabel& node) {
    ir.push_back(std::make_unique<IrLabelStmt>(node.labelname));
}
void ocarlang::IrGenerator::visit(JumpStatement& node) {
    ir.push_back(std::make_unique<IrJmp>(node.labelname, "jmp"));
}
void ocarlang::IrGenerator::visit(WhileLoop& node) {
    std::string startLabel = generateLabel();
    std::string continueLabel = generateLabel();
    std::string endLabel = generateLabel();
    std::string jumpName = condMap.at(node.cond);

    ir.push_back(std::make_unique<IrLabelStmt>(startLabel));
    node.comparison->accept(*this);
    ir.push_back(std::make_unique<IrJmp>(continueLabel, jumpName));
    ir.push_back(std::make_unique<IrJmp>(endLabel, "jmp"));
    ir.push_back(std::make_unique<IrLabelStmt>(continueLabel));
    node.scope->accept(*this);
    ir.push_back(std::make_unique<IrJmp>(startLabel, "jmp"));
    ir.push_back(std::make_unique<IrLabelStmt>(endLabel));
}
void ocarlang::IrGenerator::visit(SwapStatement& node) {
    node.left->accept(*this);
    auto left =
        get_current_as<IrMemName>("expected swaps statement left to be a valid ir memory name");

    node.right->accept(*this);
    auto right =
        get_current_as<IrMemName>("expected swaps statement right to be a valid ir memory name");

    ir.push_back(std::make_unique<IrXchg>(std::move(left), std::move(right)));
}
